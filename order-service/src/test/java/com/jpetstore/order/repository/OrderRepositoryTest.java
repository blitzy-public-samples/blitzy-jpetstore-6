    // -------------------------------------------------------------------------
    // Test 3: sequenceBasedIdGeneration
    // Validates @GeneratedValue(strategy=SEQUENCE) replaces monolith's
    // non-thread-safe OrderService.getNextId() pattern (AAP Section 0.7.3)
    // -------------------------------------------------------------------------

    /**
     * Verifies that the PostgreSQL sequence-based ID generation works correctly
     * via {@code @GeneratedValue(strategy = GenerationType.SEQUENCE)} with
     * {@code @SequenceGenerator(sequenceName = "order_id_seq")}.
     *
     * <p>This test validates the replacement of the monolith's non-thread-safe
     * {@code OrderService.getNextId()} pattern (read-then-update on the
     * {@code sequence} table) with a database-guaranteed atomic sequence.</p>
     */
    @Test
    void sequenceBasedIdGeneration() {
        // Arrange: Save two consecutive orders
        Order order1 = createTestOrder();
        Order order2 = createTestOrder();

        Order savedOrder1 = orderRepository.save(order1);
        entityManager.flush();

        Order savedOrder2 = orderRepository.save(order2);
        entityManager.flush();

        // Assert: Both have non-zero orderId values (generated, not default int)
        assertThat(savedOrder1.getOrderId()).isNotEqualTo(0);
        assertThat(savedOrder2.getOrderId()).isNotEqualTo(0);

        // Assert: Second orderId > First orderId (ascending sequence)
        assertThat(savedOrder2.getOrderId()).isGreaterThan(savedOrder1.getOrderId());
    }

    // -------------------------------------------------------------------------
    // Test 4: snakeCaseColumnMappingValidation
    // Validates all @Column(name="...") annotations produce correct column names
    // -------------------------------------------------------------------------

    /**
     * Verifies that all {@code @Column(name = "...")} annotations on the
     * {@link Order} entity produce the expected snake_case column names in the
     * database. Uses a native SQL query via {@link TestEntityManager} that
     * explicitly references every column by its expected name — if any column
     * name is incorrect, the query fails with a SQL error.
     *
     * <p>This validates the HSQLDB → PostgreSQL column name mapping documented
     * in the migration column-mapping-manifest:</p>
     * <ul>
     *   <li>{@code orderid → order_id}</li>
     *   <li>{@code shipaddr1 → ship_addr1}</li>
     *   <li>{@code totalprice → total_price}</li>
     *   <li>{@code billtofirstname → bill_to_first_name}</li>
     *   <li>... and all other columns</li>
     * </ul>
     */
    @Test
    void snakeCaseColumnMappingValidation() {
        // Arrange: Save an order with all fields populated
        Order order = createTestOrder();
        Order saved = orderRepository.save(order);
        entityManager.flush();

        // Act: Execute native SQL using exact @Column name annotations.
        // If any column name is wrong, this query throws a SQL exception.
        Object[] row = (Object[]) entityManager.getEntityManager()
                .createNativeQuery(
                        "SELECT order_id, userid, order_date, " +
                                "ship_addr1, ship_addr2, ship_city, ship_state, ship_zip, ship_country, " +
                                "bill_addr1, bill_addr2, bill_city, bill_state, bill_zip, bill_country, " +
                                "courier, total_price, " +
                                "bill_to_first_name, bill_to_last_name, " +
                                "ship_to_first_name, ship_to_last_name, " +
                                "credit_card, expr_date, card_type, locale, status " +
                                "FROM orders WHERE order_id = ?1")
                .setParameter(1, saved.getOrderId())
                .getSingleResult();

        // Assert: Query succeeded (all column names exist) and values match
        assertThat(row).isNotNull();
        assertThat(row).hasSize(26);

        // Spot-check critical column values to verify data integrity
        // row[0] = order_id
        assertThat(((Number) row[0]).intValue()).isEqualTo(saved.getOrderId());
        // row[1] = userid (the @Column name for the 'username' Java field)
        assertThat(row[1]).isEqualTo("j2ee");
        // row[3] = ship_addr1
        assertThat(row[3]).isEqualTo("Ship Address1");
        // row[11] = bill_city
        assertThat(row[11]).isEqualTo("Bill City");
        // row[16] = total_price
        assertThat(new BigDecimal(row[16].toString())).isEqualByComparingTo(new BigDecimal("2000.05"));
        // row[17] = bill_to_first_name
        assertThat(row[17]).isEqualTo("Bill First Name");
        // row[20] = ship_to_last_name
        assertThat(row[20]).isEqualTo("Ship Last Name");
        // row[21] = credit_card
        assertThat(row[21]).isEqualTo("1234 5678 9012 3456");
        // row[22] = expr_date
        assertThat(row[22]).isEqualTo("06/2022");
        // row[23] = card_type
        assertThat(row[23]).isEqualTo("Visa");
        // row[24] = locale
        assertThat(row[24]).isEqualTo("ja");
        // row[25] = status
        assertThat(row[25]).isEqualTo("P");
    }

