    // -------------------------------------------------------------------------
    // Test 1: findByUsernameOrderByOrderDateDesc
    // Replaces monolith's OrderMapperTest.getOrdersByUsername()
    // -------------------------------------------------------------------------

    /**
     * Verifies that {@link OrderRepository#findByUsernameOrderByOrderDateDesc(String)}
     * returns orders filtered by username and sorted in descending order by
     * order date. This replaces the monolith's
     * {@code OrderMapperTest.getOrdersByUsername()} which tested the
     * {@code getOrdersByUsername} MyBatis mapper method.
     *
     * <p>Validates:</p>
     * <ul>
     *   <li>Filtering: only orders for the specified user are returned</li>
     *   <li>Ordering: newest order first (DESC by orderDate)</li>
     *   <li>All 25+ field values on the first returned order match saved data</li>
     * </ul>
     */
    @Test
    void findByUsernameOrderByOrderDateDesc() {
        // Arrange: Create 2 orders for "j2ee" with different dates
        Order olderOrder = createTestOrder();
        // olderOrder has date 2018-12-31T23:59:59 from createTestOrder()

        Order newerOrder = createTestOrder();
        // Truncate to microseconds since HSQLDB/PostgreSQL TIMESTAMP has microsecond precision,
        // while LocalDateTime.now() returns nanosecond precision, causing mismatch on retrieval
        LocalDateTime newerDate = LocalDateTime.now().truncatedTo(ChronoUnit.MICROS);
        newerOrder.setOrderDate(newerDate);

        // Create 1 order for a different user "ACID" to verify filtering
        Order otherUserOrder = createTestOrder();
        otherUserOrder.setUsername("ACID");

        orderRepository.save(olderOrder);
        orderRepository.save(newerOrder);
        orderRepository.save(otherUserOrder);
        entityManager.flush();
        entityManager.clear();

        // Act
        List<Order> orders = orderRepository.findByUsernameOrderByOrderDateDesc("j2ee");

        // Assert: Result list has exactly 2 orders (ACID user excluded)
        assertThat(orders).hasSize(2);

        // Assert: First order has the newer date (DESC ordering)
        assertThat(orders.get(0).getOrderDate()).isAfter(orders.get(1).getOrderDate());

        // Assert: Verify ALL field values on the first returned order
        Order firstOrder = orders.get(0);
        assertThat(firstOrder.getUsername()).isEqualTo("j2ee");
        assertThat(firstOrder.getOrderDate()).isEqualTo(newerDate);
        assertThat(firstOrder.getTotalPrice()).isEqualByComparingTo(new BigDecimal("2000.05"));
        assertThat(firstOrder.getCardType()).isEqualTo("Visa");
        assertThat(firstOrder.getCreditCard()).isEqualTo("1234 5678 9012 3456");
        assertThat(firstOrder.getExpiryDate()).isEqualTo("06/2022");
        assertThat(firstOrder.getCourier()).isEqualTo("Courier");
        assertThat(firstOrder.getLocale()).isEqualTo("ja");
        assertThat(firstOrder.getStatus()).isEqualTo("P");
        assertThat(firstOrder.getBillAddress1()).isEqualTo("Bill Address1");
        assertThat(firstOrder.getBillAddress2()).isEqualTo("Bill Address2");
        assertThat(firstOrder.getBillCity()).isEqualTo("Bill City");
        assertThat(firstOrder.getBillState()).isEqualTo("Bill State");
        assertThat(firstOrder.getBillZip()).isEqualTo("80001");
        assertThat(firstOrder.getBillCountry()).isEqualTo("USA");
        assertThat(firstOrder.getShipAddress1()).isEqualTo("Ship Address1");
        assertThat(firstOrder.getShipAddress2()).isEqualTo("Ship Address2");
        assertThat(firstOrder.getShipCity()).isEqualTo("Ship City");
        assertThat(firstOrder.getShipState()).isEqualTo("Ship State");
        assertThat(firstOrder.getShipZip()).isEqualTo("70001");
        assertThat(firstOrder.getShipCountry()).isEqualTo("JPN");
        assertThat(firstOrder.getBillToFirstName()).isEqualTo("Bill First Name");
        assertThat(firstOrder.getBillToLastName()).isEqualTo("Bill Last Name");
        assertThat(firstOrder.getShipToFirstName()).isEqualTo("Ship First Name");
        assertThat(firstOrder.getShipToLastName()).isEqualTo("Ship Last Name");

        // Verify second order has the older date
        Order secondOrder = orders.get(1);
        assertThat(secondOrder.getUsername()).isEqualTo("j2ee");
        assertThat(secondOrder.getOrderDate()).isEqualTo(LocalDateTime.of(2018, 12, 31, 23, 59, 59));
    }

